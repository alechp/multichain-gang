import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const chainFiles = ["solana", "ethereum", "bnb-chain", "bitcoin", "zcash", "robinhood-chain"];

function readJson(relativePath) {
  return JSON.parse(fs.readFileSync(path.join(root, relativePath), "utf8"));
}

export function readSourceData() {
  const taxonomy = readJson("data/chain-tools/taxonomy.json");
  const canonical = readJson("data/chain-tools/canonical-tools.json");
  const chains = Object.fromEntries(chainFiles.map((slug) => [slug, readJson(`data/chain-tools/${slug}.json`)]));
  return { taxonomy, canonical, chains };
}

export function createCatalog(source = readSourceData()) {
  return {
    schemaVersion: 1,
    verified: source.taxonomy.verified,
    taxonomy: source.taxonomy,
    tools: source.canonical.tools,
    chainOrder: [...chainFiles],
    chains: source.chains,
  };
}

export function renderCatalog(source = readSourceData()) {
  const serialized = JSON.stringify(createCatalog(source))
    .replace(/</g, "\\u003c")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
  return `/* Generated by scripts/build-chain-tools-catalog.mjs. Do not edit by hand. */\n(function installChainToolsCatalog(global) {\n  "use strict";\n  function deepFreeze(value) {\n    if (!value || typeof value !== "object" || Object.isFrozen(value)) return value;\n    Object.getOwnPropertyNames(value).forEach(function freezeChild(key) { deepFreeze(value[key]); });\n    return Object.freeze(value);\n  }\n  var catalog = ${serialized};\n  Object.defineProperty(global, "SCOPE_CHAIN_TOOLS", { value: deepFreeze(catalog), configurable: false, enumerable: true, writable: false });\n})(window);\n`;
}

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

export function renderNoscript(source = readSourceData()) {
  const tools = new Map(source.canonical.tools.map((tool) => [tool.id, tool]));
  const categories = new Map(source.taxonomy.categories.map((category) => [category.id, category]));
  const lines = [
    "<!-- Generated by scripts/build-chain-tools-catalog.mjs. Do not edit by hand. -->",
    '<div class="tools-noscript-index" aria-labelledby="tools-static-title">',
    '  <h2 id="tools-static-title">Chain Tools — verified landscapes</h2>',
    `  <p>Evidence snapshot ${escapeHtml(source.taxonomy.verified)}. Browse six chain inventories without JavaScript. These lists are documentation, not rankings or endorsements.</p>`,
    '  <nav aria-label="Static chain tooling pages">',
    "    <ul>",
    ...chainFiles.map((slug) => `      <li><a href="#tools-static-${escapeHtml(slug)}">${escapeHtml(source.chains[slug].name)} tools</a></li>`),
    "    </ul>",
    "  </nav>",
  ];

  for (const slug of chainFiles) {
    const chain = source.chains[slug];
    const nativeGaps = chain.coverage.filter((entry) => entry.level === "native-gap");
    lines.push(
      `  <section id="tools-static-${escapeHtml(slug)}" aria-labelledby="tools-static-${escapeHtml(slug)}-title">`,
      `    <h3 id="tools-static-${escapeHtml(slug)}-title">${escapeHtml(chain.name)} tooling landscape</h3>`,
      `    <p>${escapeHtml(chain.scopeStatement)} Verified ${escapeHtml(chain.verified)}.</p>`,
    );
    if (nativeGaps.length) {
      lines.push("    <div class=\"tools-noscript-gaps\">", "      <h4>Explicit native gaps</h4>", "      <ul>");
      for (const gap of nativeGaps) {
        lines.push(`        <li><strong>${escapeHtml(categories.get(gap.categoryId).name)}:</strong> ${escapeHtml(gap.note)}</li>`);
      }
      lines.push("      </ul>", "    </div>");
    } else {
      lines.push("    <p><strong>Native gaps:</strong> no category is labeled as a native gap in this curated snapshot; review scope and risk per row.</p>");
    }
    lines.push(
      "    <table>",
      `      <caption>${escapeHtml(chain.name)} tools (${chain.placements.length} verified placements)</caption>`,
      "      <thead><tr><th scope=\"col\">Tool</th><th scope=\"col\">Categories</th><th scope=\"col\">Scope</th><th scope=\"col\">State</th><th scope=\"col\">First official source</th></tr></thead>",
      "      <tbody>",
    );
    for (const placement of chain.placements) {
      const tool = tools.get(placement.toolId);
      const categoryNames = placement.categories.map((id) => categories.get(id).name).join(", ");
      const evidence = placement.evidence[0];
      lines.push(
        `        <tr data-placement-id="${escapeHtml(placement.id)}"><th scope="row">${escapeHtml(placement.displayName || tool.name)}</th><td>${escapeHtml(categoryNames)}</td><td>${escapeHtml(placement.scope)}</td><td>${escapeHtml(placement.status)}</td><td><a href="${escapeHtml(evidence.url)}">${escapeHtml(evidence.grade)} source ↗</a></td></tr>`,
      );
    }
    lines.push("      </tbody>", "    </table>");
    if (chain.gaps.length) {
      lines.push("    <h4>Native gaps and category traps</h4>", "    <ul>");
      for (const gap of chain.gaps) lines.push(`      <li>${escapeHtml(gap)}</li>`);
      lines.push("    </ul>");
    }
    lines.push(`    <p><a href="${escapeHtml(chain.hubRoute)}">Read ${escapeHtml(chain.name)} chain articles</a></p>`, "  </section>");
  }
  lines.push("</div>", "");
  return lines.join("\n");
}

export function generatedTargets(source = readSourceData()) {
  return new Map([
    [path.join(root, "data/chain-tools/catalog.js"), renderCatalog(source)],
    [path.join(root, "data/chain-tools/noscript.html"), renderNoscript(source)],
  ]);
}

export function checkGenerated(source = readSourceData()) {
  const stale = [];
  for (const [target, expected] of generatedTargets(source)) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
    if (current !== expected) stale.push(path.relative(root, target));
  }
  return stale;
}

function main() {
  const source = readSourceData();
  if (process.argv.includes("--check")) {
    const stale = checkGenerated(source);
    if (stale.length) {
      console.error(`Stale generated Chain Tools files:\n${stale.map((file) => `- ${file}`).join("\n")}`);
      process.exitCode = 1;
      return;
    }
    console.log("Chain Tools compiled catalog and no-JavaScript mirror are current.");
    return;
  }
  for (const [target, contents] of generatedTargets(source)) fs.writeFileSync(target, contents);
  console.log("Generated data/chain-tools/catalog.js and data/chain-tools/noscript.html.");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
